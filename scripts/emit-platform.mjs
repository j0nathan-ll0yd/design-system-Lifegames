/**
 * emitPlatform — shared CSS-var platform emitter for alias-mapped token platforms.
 *
 * Used by shadcn (B1) and material3 (B2) platform configs. Each platform provides:
 *   - name:       platform identifier (used in comments)
 *   - aliasMap:   { 'platform-role': '{semantic.token.path}' | resolvedValue }
 *   - tokens:     resolved token array from resolveAllTokens()
 *   - transform:  optional fn(resolvedValue, tokenType) → string for value transformation
 *   - header:     optional string prepended to output (default: generated comment)
 *
 * Returns the emitted CSS string (does NOT write to disk — caller decides path).
 */

/**
 * @param {object} opts
 * @param {string} opts.name
 * @param {Record<string, string>} opts.aliasMap
 * @param {Array<{path: string[], $type: string, resolvedValue: unknown}>} opts.tokens
 * @param {((value: unknown, type: string) => string) | undefined} opts.transform
 * @param {string | undefined} opts.header
 * @returns {string}
 */
export function emitPlatform({name, aliasMap, tokens, transform, header}) {
  const tokenMap = new Map()
  for (const t of tokens) {
    tokenMap.set(t.path.join('.'), t)
  }

  function resolveAlias(ref) {
    if (typeof ref !== 'string') {
      return {value: ref, type: null}
    }
    if (ref.startsWith('{') && ref.endsWith('}')) {
      const path = ref.slice(1, -1)
      const t = tokenMap.get(path)
      if (!t) {
        throw new Error(`emitPlatform(${name}): unresolved alias reference "${ref}"`)
      }
      return {value: t.resolvedValue, type: t.$type}
    }
    return {value: ref, type: null}
  }

  const defaultHeader = `/* Generated by Style Dictionary — ${name} platform — do not edit */\n`
  let out = header !== undefined ? header : defaultHeader

  out += ':root {\n'
  for (const [role, ref] of Object.entries(aliasMap)) {
    const {value, type} = resolveAlias(ref)
    const emitted = transform ? transform(value, type ?? '') : String(value ?? '')
    out += `  --${role}: ${emitted};\n`
  }
  out += '}\n'

  return out
}
